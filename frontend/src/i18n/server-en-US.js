const messagePatterns = [
  [/^([A-Z]{3}) 金额最多支持 (\d+) 位小数$/, '$1 amounts support up to $2 decimal places.'],
  [/^已安排 (\d+) 分钟后关机$/, 'Shutdown scheduled in $1 min.'],
  [/^已安排 MacBook (\d+) 分钟后关机$/, 'MacBook shutdown scheduled in $1 min.'],
  [/^(MacBook|Windows) · (\d+) 分钟后关机$/, '$1 · Shut down in $2 min'],
  [/^已切换到(.+)模式$/, 'Switched to $1 mode.'],
  [/^(.+) 负载已持续回落。$/, '$1 load has remained below the task threshold.'],
];

const diskSpace = /^(.+) 剩余 (\d+\.\d{2}) GiB$/;

export function translateServerPattern(message) {
  if (typeof message !== 'string') return message;
  for (const [pattern, replacement] of messagePatterns) {
    if (pattern.test(message)) return message.replace(pattern, replacement);
  }
  const volumes = message.split('，');
  if (volumes.every((volume) => diskSpace.test(volume))) {
    return volumes.map((volume) => volume.replace(diskSpace, '$1 has $2 GiB free')).join(', ');
  }
  return message;
}
